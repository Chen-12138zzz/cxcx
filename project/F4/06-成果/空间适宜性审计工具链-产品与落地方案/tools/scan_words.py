"""
F4 幻灯片源（.slide）违规词扫描。

【为什么禁用词要拆成片段再拼接】
本脚本位于 project/F4 之内，因此**它自己也在 consistency_check 的扫描范围内**。
若把违规词直接写成长度完整的字符串，脚本源码就会在正式校验里报出一堆命中
（F1 那份实测过：源码里的禁用词字面量导致 4 处"废弃值残留"）。
⇒ 因此所有禁用词一律 `A + B` 拼接，源码不含完整词形，运行时再 join。
   这比"把本文件加进 baseline 的 allow_in"更干净 —— 不削弱基线。

【★ 为什么必须做「否定语境放行」】
本片的许多必要表述天然会命中禁用词 —— 因为**声明边界**这件事本身就要提到那些词：
  · "不产出任何选址结论"      → 命中「任何」
  · "不产选址图、不给选址建议" → 命中「选址建议」
  · "不存在实测准确率这一档"   → 命中「实测准确率」
朴素子串匹配会把它们全部报出来，噪声大到工具会被弃用
（consistency_check 头部原话：「滥报会让工具被弃用」）。
⇒ 因此本脚本在匹配点**前 20 字**内查找否定词（不/未/无/非/禁/避免/没有…），
   命中即判定为「声明边界」，计入放行数并在末尾汇总，不作为候选报出。
   这**不是**放宽标准：真正的违规（肯定式断言）没有否定词，仍会被报出。

【本脚本查什么（F4 专属）】
  · 门禁 C / 通用红线：全称否定与"首个/首创"式表述
  · G-1：选址结论式表述（适合养殖 / 建议划为 / 推荐选址）
  · G-2：把合成场说成真实地理适宜性
  · G-3：预设"融合一定更好"
  · K-5 / 数据模式：本项目不存在的"实测准确率"档位
  · D-1：已落地 / 已上线 / 已服务 / 已产生收入式声称
  · SC-06：超链接
  · 占位符：【待填】/ TODO / XXX
"""
import os
import re

BASE = (r"E:/BJTU/CXCY/CXCY-PAPER/project/F4/06-成果/"
        r"空间适宜性审计工具链-产品与落地方案/slides")

# ---- 禁用词（片段拼接，源码不含完整词形） ----
_F = {
    "全称否定A": "完全" + "空白",
    "全称否定B": "尚属" + "空白",
    "全称否定C": "未检索到" + "同类",
    "全称否定D": "无人" + "研究",
    "全称否定E": "没有" + "人",
    "首个式": "国内" + "首个",
}

# 否定语境标记：出现在匹配点前 20 字内，即视为「声明边界」而非违规
NEG = ("不", "未", "无", "非", "禁", "避免", "没有", "排除", "拒绝", "免于")

PATS = [
    # 全称表述候选
    (r"仅见", "全称：仅见"),
    (r"所有[^。\n]{0,8}(数据|模型|研究|方法)", "全称：所有"),
    (r"任何[^。\n]{0,8}(情况|结论|地块|塘口|数据|单位)", "全称：任何"),

    # D-1 现状口径：只允许「已完成交付」，不允许「已落地 / 已服务」
    (r"已落地|已上线|已服务|已合作|已产生收入|已签约|已交付给|已部署到",
     "D-1 已落地声称（本片只允许『已完成交付』）"),

    # 门禁 C
    (r"首创|首家|唯一一家", "门禁 C"),
    (_F["首个式"], "门禁 C"),
    (_F["全称否定A"], "门禁 C"),
    (_F["全称否定B"], "门禁 C"),
    (_F["全称否定C"], "门禁 C"),
    (_F["全称否定D"], "门禁 C"),
    (_F["全称否定E"], "门禁 C"),

    # G-1 不得产出选址结论
    (r"适合养殖|不适合养殖|宜养|建议划为|推荐选址|选址建议|建议优先",
     "G-1 选址结论式表述"),
    (r"限养区|适养区|禁养区", "G-6 行政/政策建议"),

    # G-2 不得把合成场说成真实地理适宜性
    (r"真实[^。\n]{0,6}(适宜性|地理)|实测[^。\n]{0,4}适宜性",
     "G-2 合成场不得表述为真实地理适宜性"),

    # G-3 不得预设融合方向
    (r"融合[^。\n]{0,6}(一定|必然|定会)[^。\n]{0,4}(更|提升|提高)",
     "G-3 预设融合方向"),

    # K-5 / 数据模式
    (r"实测准确率|实测精度|真实准确率|准确率达|精度达到",
     "K-5 本项目不存在『实测准确率』这一档"),

    # 定位禁忌（慎用）
    (r"平台", "定位禁忌（慎用）"),

    # SC-06 超链接
    (r"href", "[SC-06] 超链接"),

    # 占位符
    (r"【待填】|TODO|XXX|待填|Lorem", "占位符"),
]


def negated(text: str, start: int, win: int = 20) -> bool:
    """匹配点前 win 字内是否含否定词 —— 有则判为「声明边界」。"""
    return any(n in text[max(0, start - win):start] for n in NEG)


if __name__ == "__main__":
    n_cand = n_pass = 0
    for n in sorted(os.listdir(BASE)):
        t = open(os.path.join(BASE, n), encoding="utf-8").read()
        cand, passed = [], []
        for rx, label in PATS:
            for m in re.finditer(rx, t):
                s = max(0, m.start() - 26)
                e = min(len(t), m.end() + 26)
                ctx = t[s:e].replace("\n", " ")
                if negated(t, m.start()):
                    passed.append(f"{label}:{m.group(0)}")
                else:
                    cand.append(f"    [{label}] …{ctx}…")
        if cand:
            n_cand += len(cand)
            print(f"== {n}  ← 需人工确认")
            for h in cand:
                print(h)
        if passed:
            n_pass += len(passed)
            print(f"   ({n} 另有 {len(passed)} 处落在否定语境，已放行："
                  f"{', '.join(passed[:6])}{' …' if len(passed) > 6 else ''})")
    print(f"--- done  候选 {n_cand} 处 | 否定语境放行 {n_pass} 处")
    print("    候选=0 时，说明没有肯定式违规表述。")
